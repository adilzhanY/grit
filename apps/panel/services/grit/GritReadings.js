const READINGS = [LIGURIA];

/** The reading a task title opts into, or null. */
function readingFor(title) {
    const t = String(title ?? "").toLowerCase();
    if (t.length === 0)
        return null;
    if (t.indexOf("liguria") >= 0 || t.indexOf("лигур") >= 0)
        return LIGURIA;
    return null;
}

/** Every line of a reading, flattened, for word/line counts. */
function lineCount(reading) {
    if (!reading)
        return 0;
    return reading.stanzas.reduce((n, s) => n + s.length, 0);
}

/**
 * A line as rich text with each stressed vowel set in bold and tinted, so the
 * eye lands on the stress without having to hunt for the accent mark. Bold
 * carries it on its own: a monochrome theme has no accent colour to give.
 *
 * Qt's rich text ignores <span style="color:...">, so this uses <font color>.
 * QML stringifies an opaque color as #AARRGGBB, which HTML does not
 * understand, hence the alpha strip.
 */
function markup(line, color) {
    var hex = String(color);
    if (hex.length === 9 && hex.charAt(0) === "#")
        hex = "#" + hex.substring(3);
    return String(line)
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/([Ѐ-ӿ])́/g,
            '<b><font color="' + hex + '">$1́</font></b>');
}
